import React from 'react';
import { Sparkles } from 'lucide-react';
import { tagClass } from '@/components/shared/Badges';
import { CitationChip } from '@/components/shared/CitationChip';
import { useEvidenceInspector } from '@/hooks/useEvidenceInspector';
import { CaseWorkspace, ReconstructionDetail } from '@/types/api';
import type { SceneFile } from '@/features/crime-scene/case-scene/sceneFile';

/**
 * What a generated scenario rests on: who wrote its scene script, its assumptions and the
 * evidence behind it, and what the evidence leaves open. Shown instead of the plain
 * assumptions paragraph for scenarios generated from the evidence.
 */
export const SceneScriptPanel: React.FC<{ reconstruction: ReconstructionDetail; workspace: CaseWorkspace }> = ({ reconstruction, workspace }) => {
  const scene = reconstruction.scene as unknown as SceneFile | null;
  const { open } = useEvidenceInspector();
  if (!scene?.generated) return null;
  const g = scene.generated;
  const assumptions = scene.scenario?.assumptions ?? [];
  const sources = (scene.scenario?.supported_by ?? [])
    .map((ref) => ({ ref, evidence: workspace.evidence.find((e) => e.id === ref.evidence_id) }))
    .filter((x) => !!x.evidence);

  return (
    <section className="max-w-4xl space-y-3 rounded-md border border-line p-3" aria-label="Scene script">
      <div className="flex flex-wrap items-center gap-2">
        <span className={`${tagClass} border-accent/40 bg-accent/10 text-accent-text`}>
          <Sparkles className="size-3" aria-hidden />
          {g.by === 'gemini' ? `Generated by Gemini` : 'Drafted from the case records'}
        </span>
        <span className="text-2xs text-ink-muted">
          {g.by === 'gemini' ? g.model : 'without AI'} · {new Date(g.at).toLocaleString()}
        </span>
      </div>
      {g.summary && <p className="text-body text-ink-soft">{g.summary}</p>}
      <div className="grid gap-3 md:grid-cols-2">
        {assumptions.length > 0 && (
          <div>
            <div className="text-xs font-medium text-ink-muted">Assumptions</div>
            <ul className="mt-1 list-disc space-y-0.5 pl-4 text-body text-ink-soft">
              {assumptions.map((a) => (
                <li key={a}>{a}</li>
              ))}
            </ul>
          </div>
        )}
        {g.open_questions.length > 0 && (
          <div>
            <div className="text-xs font-medium text-ink-muted">Open questions</div>
            <ul className="mt-1 list-disc space-y-0.5 pl-4 text-body text-ink-soft">
              {g.open_questions.map((q) => (
                <li key={q}>{q}</li>
              ))}
            </ul>
          </div>
        )}
      </div>
      {sources.length > 0 && (
        <div className="flex flex-wrap items-baseline gap-x-3 gap-y-1">
          <span className="text-xs font-medium text-ink-muted">Supported by</span>
          {sources.map(({ ref, evidence }) => (
            <CitationChip
              key={ref.evidence_id}
              citation={{ evidence_id: ref.evidence_id, evidence_title: evidence!.title, page: null }}
              onOpen={() => open(ref.evidence_id, ref.passage)}
            />
          ))}
        </div>
      )}
      {g.warnings.length > 0 && (
        <details className="text-xs text-ink-muted">
          <summary className="cursor-pointer">
            {g.warnings.length} {g.warnings.length === 1 ? 'note' : 'notes'} on how the script was checked
          </summary>
          <ul className="mt-1 list-disc space-y-0.5 pl-4">
            {g.warnings.map((w) => (
              <li key={w}>{w}</li>
            ))}
          </ul>
        </details>
      )}
    </section>
  );
};
