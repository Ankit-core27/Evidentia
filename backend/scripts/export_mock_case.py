"""Writes the Sahyadri Chowk case to frontend/src/mocks/sahyadri.json, so mock mode
(`npm run dev:mock`) shows the same case as the real backend.

    python scripts/export_mock_case.py

It seeds a throwaway database with app.seed and reads the case back through the API,
so every record has exactly the shape and id the backend serves. Run it again after
changing app/seed_sahyadri.py.
"""

import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

TMP_DIR = Path(tempfile.mkdtemp(prefix="evidentia-mock-export-"))
os.environ["DATABASE_URL"] = f"sqlite:///{TMP_DIR / 'export.db'}"
os.environ["STORAGE_DIR"] = str(TMP_DIR / "storage")
os.environ["GEMINI_API_KEY"] = ""
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from fastapi.testclient import TestClient  # noqa: E402
from sqlalchemy import select  # noqa: E402

from app import seed_sahyadri as sahyadri  # noqa: E402
from app.core.config import REPO_ROOT, get_settings  # noqa: E402
from app.core.db import SessionLocal, engine  # noqa: E402
from app.main import app  # noqa: E402
from app.models import Base, EvidenceLink, Investigator  # noqa: E402
from app.seed import seed  # noqa: E402

OUT = REPO_ROOT / "frontend" / "src" / "mocks" / "sahyadri.json"


def main() -> None:
    get_settings.cache_clear()
    Base.metadata.create_all(engine)
    with SessionLocal() as db:
        seed(db)
    case_id = sahyadri.CASE_KEY
    with TestClient(app) as client:

        def get(path: str):
            response = client.get(f"/api{path}")
            response.raise_for_status()
            return response.json()

        workspace = get(f"/cases/{case_id}/workspace")
        evidence_ids = [e["id"] for e in workspace["evidence"]]
        evidence = []
        texts = sahyadri.evidence_texts()
        keys = [key for key, *_ in sahyadri.EVIDENCE]
        for evidence_id, key in zip(evidence_ids, keys, strict=True):
            row = get(f"/evidence/{evidence_id}")
            evidence.append(
                {k: row[k] for k in workspace["evidence"][0]}
                | {"extracted_text": row["extracted_text"], "pages": texts[key]}
            )
        reconstructions = []
        stages = []
        scene_objects = []
        annotations = []
        for summary in get(f"/cases/{case_id}/reconstructions"):
            detail = get(f"/reconstructions/{summary['id']}")
            reconstructions.append(summary | {"scene": detail["scene"]})
            for stage in detail["stages"]:
                scene_objects.extend(stage.pop("scene_objects"))
                stages.append(stage)
            annotations.extend(detail["annotations"])
        reports = [get(f"/reports/{r['id']}") for r in get(f"/cases/{case_id}/reports")]
        observations = get(f"/cases/{case_id}/observations")
        conflicts = get(f"/cases/{case_id}/conflicts")
        audit = get(f"/cases/{case_id}/audit")

    with SessionLocal() as db:
        lead = db.get(Investigator, workspace["case"]["lead_investigator_id"])
        links = [
            {"evidence_id": x.evidence_id, "target_type": x.target_type, "target_id": x.target_id, "passage": x.passage}
            for x in db.scalars(
                select(EvidenceLink).where(EvidenceLink.evidence_id.in_(evidence_ids)).order_by(EvidenceLink.id)
            )
        ]
    investigator = {
        "id": lead.id,
        "name": lead.name,
        "badge_number": lead.badge_number,
        "role": lead.role,
        "clearance_level": lead.clearance_level,
    }

    fixture = {
        "_source": "Generated by backend/scripts/export_mock_case.py from app/seed_sahyadri.py. Do not edit by hand.",
        "investigators": [investigator],
        "case": workspace["case"],
        "evidence": evidence,
        "persons": workspace["persons"],
        "objects": workspace["objects"],
        "locations": workspace["locations"],
        "events": workspace["events"],
        "relationships": workspace["relationships"],
        "observations": observations,
        "conflicts": conflicts,
        "injuries": workspace["injuries"],
        "reconstructions": reconstructions,
        "stages": stages,
        "sceneObjects": scene_objects,
        "annotations": annotations,
        "reports": reports,
        "links": links,
        "audit": audit,
    }
    OUT.write_text(json.dumps(fixture, indent=1, ensure_ascii=False) + "\n", "utf-8")
    print(f"Wrote {OUT.relative_to(REPO_ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    try:
        main()
    finally:
        shutil.rmtree(TMP_DIR, ignore_errors=True)
